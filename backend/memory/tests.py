import json
from unittest.mock import patch
from django.test import TestCase, Client
from django.contrib.auth import get_user_model
from memory.models import ContentReport

User = get_user_model()


class ContentReportTests(TestCase):
    def setUp(self):
        self.client = Client()
        self.user = User.objects.create_user(
            email="tester@example.com",
            name="Test User",
            password="testpassword123",
        )

    @patch("authentication.email_service.send_brevo_email", return_value=True)
    def test_submit_report_creates_record_and_dispatches_email(self, mock_email):
        payload = {
            "content_type": "message",
            "content_id": "msg-12345",
            "persona_id": "persona-abc",
            "persona_name": "Kim Taehyung",
            "reported_text": "Offensive text generated by bot",
            "reason": "Harmful, violent, or dangerous content",
            "details": "This bot suggested dangerous activity",
            "user_id": str(self.user.id),
        }

        response = self.client.post(
            "/api/memory/report/",
            data=json.dumps(payload),
            content_type="application/json",
        )

        self.assertEqual(response.status_code, 201)
        data = response.json()
        self.assertTrue(data["success"])
        self.assertTrue(data["email_sent"])
        self.assertIn("report_id", data)

        report = ContentReport.objects.filter(id=data["report_id"]).first()
        self.assertIsNotNone(report)
        self.assertEqual(report.content_type, "message")
        self.assertEqual(report.persona_name, "Kim Taehyung")
        self.assertEqual(report.reporter_email, "tester@example.com")
        self.assertEqual(report.reason, "Harmful, violent, or dangerous content")
        self.assertEqual(report.status, "pending")

        mock_email.assert_called_once()
        args = mock_email.call_args[0]
        self.assertEqual(args[0], "tester@example.com")
        self.assertIn("Content Report Acknowledgment", args[2])

    def test_submit_report_requires_reason(self):
        payload = {
            "content_type": "message",
            "persona_name": "Kim Taehyung",
            "reason": "",
        }
        response = self.client.post(
            "/api/memory/report/",
            data=json.dumps(payload),
            content_type="application/json",
        )
        self.assertEqual(response.status_code, 400)
        data = response.json()
        self.assertFalse(data["success"])
        self.assertEqual(data["error"], "A report reason is required.")
